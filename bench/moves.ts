// Shared fixtures for the benchmark: boards of a given shape and a seeded sequence of valid moves,
// so both implementations run exactly the same work.
import { Board } from "../packages/core/src/index.ts";
import { ArrayBoard } from "./array-board.ts";

export type Move = { id: string; toListId: string; beforeCardId: string | null };
export type Shape = { lists: number; cardsPerList: number };

/** mulberry32: a tiny seeded PRNG, so every run uses the same moves. */
function random(seed: number): () => number {
  let a = seed;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const listId = (l: number) => `L${l}`;
const cardId = (l: number, c: number) => `L${l}C${c}`;

export function makeBoard(shape: Shape): Board<{ id: string }, { id: string }> {
  const board = new Board<{ id: string }, { id: string }>();
  for (let l = 0; l < shape.lists; l++) {
    board.addList({ id: listId(l) }, null);
    for (let c = 0; c < shape.cardsPerList; c++)
      board.addCard(listId(l), { id: cardId(l, c) }, null);
  }
  return board;
}

export function makeArrayBoard(shape: Shape): ArrayBoard<{ id: string }> {
  const board = new ArrayBoard<{ id: string }>();
  for (let l = 0; l < shape.lists; l++) {
    board.addList(listId(l));
    for (let c = 0; c < shape.cardsPerList; c++) board.addCard(listId(l), { id: cardId(l, c) });
  }
  return board;
}

/** `count` valid random moves, generated by replaying them on an ArrayBoard as it goes. */
export function makeMoves(shape: Shape, count: number, seed = 1): Move[] {
  const next = random(seed);
  const pick = <T>(items: readonly T[]): T => items[Math.floor(next() * items.length)] as T;
  const replay = makeArrayBoard(shape);
  const moves: Move[] = [];
  while (moves.length < count) {
    const from = pick(replay.lists.filter((l) => l.cards.length > 0));
    const id = pick(from.cards).id;
    const to = pick(replay.lists);
    const beforeCardId = next() < 0.1 || to.cards.length === 0 ? null : pick(to.cards).id;
    const move = { id, toListId: to.id, beforeCardId };
    replay.moveCard(move.id, move.toListId, move.beforeCardId);
    moves.push(move);
  }
  return moves;
}
